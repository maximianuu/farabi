"""Calibration sequences (lists of token ids) for the GPTQ pass: mixed text that resembles real use of the model.

The published weights were calibrated with a private superset of this recipe (about 58k tokens: thinking chats, question/answer
chats, one chat behind a long system prompt, technical prose, source code, a tool-calling chat and JSON answers). This file
reproduces the METHOD with shareable data:

  1. thinking chats                      calibration_thinking.json (generated by the model itself)
  2. your own chats (optional)           calibration_data/*.json   - each file: a list of {"role", "content"} messages
  3. one long-system-prompt chat (opt.)  calibration_data/system_prompt.txt
  4. prose and code                      calibration_data/*.txt|*.md|*.py|*.swift|*.c|*.rs|*.js  + a few standard-library docstrings
  5. a tool-calling chat
  6. JSON answers

Weights produced with it are close to, but not bit-identical with, the published ones. Keep calibration text disjoint from
whatever you use to measure fidelity afterwards.
"""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "calibration_data")


def sequences(tok, max_len=3072):
    D = []
    encode = lambda s: tok.encode(s, add_special_tokens=False)
    template = lambda m, **kw: tok.apply_chat_template(m, tokenize=False, **kw)

    # 1) thinking chats
    thinking = json.load(open(os.path.join(HERE, "calibration_thinking.json"), encoding="utf-8"))
    for x in thinking:
        if not x["answer"]:
            continue
        t = template([{"role": "user", "content": x["question"]}], add_generation_prompt=True, enable_thinking=True)
        D.append(encode(t + x["thinking"].strip() + "\n</think>\n\n" + x["answer"].strip() + "<|im_end|>\n"))

    # 2) your own chats
    for path in sorted(glob.glob(os.path.join(DATA, "*.json"))):
        try:
            messages = json.load(open(path, encoding="utf-8"))
            D.append(encode(template(messages, add_generation_prompt=False, enable_thinking=False)))
        except Exception as e:
            print(f"calibration: skipped {os.path.basename(path)} ({type(e).__name__}: {e})")

    # 3) a long system prompt followed by one thinking turn; kept whole so the long context is seen in one piece
    whole = []
    system_path = os.path.join(DATA, "system_prompt.txt")
    if os.path.exists(system_path) and thinking:
        x = thinking[min(3, len(thinking) - 1)]
        system = {"role": "system", "content": open(system_path, encoding="utf-8").read()}
        t = template([system, {"role": "user", "content": x["question"]}], add_generation_prompt=True, enable_thinking=True)
        whole = [list(map(int, encode(t + x["thinking"].strip() + "\n</think>\n\n" + x["answer"].strip() + "<|im_end|>\n")))]

    # 4) prose and code
    for pattern in ("*.txt", "*.md", "*.py", "*.swift", "*.c", "*.rs", "*.js"):
        for path in sorted(glob.glob(os.path.join(DATA, pattern))):
            if os.path.basename(path) == "system_prompt.txt":
                continue
            text = open(path, encoding="utf-8", errors="ignore").read()
            for start in range(0, min(len(text), 36000), 9000):
                piece = text[start:start + 9000]
                if len(piece) > 2000:
                    D.append(encode(piece))
    import argparse
    import textwrap
    D.append(encode((argparse.__doc__ or "") + "\n\n" + (json.__doc__ or "") + "\n\n" + (textwrap.__doc__ or "")))

    # 5) a tool-calling chat
    tools = [{"type": "function", "function": {"name": "read_file", "description": "Reads the contents of a file.",
                                               "parameters": {"type": "object", "properties": {"path": {"type": "string"}, "lines": {"type": "integer"}}, "required": ["path"]}}},
             {"type": "function", "function": {"name": "python", "description": "Runs Python code and returns its output.",
                                               "parameters": {"type": "object", "properties": {"code": {"type": "string"}}, "required": ["code"]}}},
             {"type": "function", "function": {"name": "web_search", "description": "Searches the web.",
                                               "parameters": {"type": "object", "properties": {"query": {"type": "string"}}, "required": ["query"]}}}]
    messages = [{"role": "system", "content": "You are a helpful assistant. Use the tools when needed."},
                {"role": "user", "content": "Multiply 48291 by 7364, then tell me the sum of the digits of the result."},
                {"role": "assistant", "content": "", "tool_calls": [{"type": "function", "function": {"name": "python", "arguments": {"code": "n = 48291 * 7364\nprint(n, sum(int(c) for c in str(n)))"}}}]},
                {"role": "tool", "content": "355614924 36"},
                {"role": "assistant", "content": "48291 x 7364 = **355,614,924**; the digits add up to **36**."},
                {"role": "user", "content": "Show the first 20 lines of ~/notes/plan.md."},
                {"role": "assistant", "content": "", "tool_calls": [{"type": "function", "function": {"name": "read_file", "arguments": {"path": "~/notes/plan.md", "lines": 20}}}]},
                {"role": "tool", "content": "# Plan\n1. Finish the engine\n2. Run the tests\n3. Write the docs"},
                {"role": "assistant", "content": "The file has 4 lines:\n\n```\n# Plan\n1. Finish the engine\n2. Run the tests\n3. Write the docs\n```"}]
    D.append(encode(template(messages, tools=tools, add_generation_prompt=False, enable_thinking=False)))

    # 6) JSON answers
    messages = []
    for question, answer in (
            ("Does this message need a web search? \"What is the dollar exchange rate today?\" Return JSON.",
             {"needed": True, "question": "Today's dollar exchange rate", "queries": ["dollar exchange rate today"], "news": False}),
            ("Extract the fields from the invoice: Invoice No AK2025110342, date 2026-03-14, seller Example Trading Ltd., total 12,480.50 EUR.",
             {"invoice_no": "AK2025110342", "date": "2026-03-14", "company": "Example Trading Ltd.", "total": "12480.50"}),
            ("Plan JSON for the message \"Hi, how are you?\".",
             {"needed": False, "question": "Greeting", "queries": [], "news": False}),
            ("Give a title and three tags as JSON for: A new smartwatch with 14 days of battery life was announced.",
             {"title": "Smartwatch with 14-day battery life announced", "tags": ["smartwatch", "wearables", "battery life"]})):
        messages += [{"role": "user", "content": question + " Return only JSON."}, {"role": "assistant", "content": json.dumps(answer, ensure_ascii=False, indent=2)}]
    D.append(encode(template(messages, add_generation_prompt=False, enable_thinking=False)))

    out = list(whole)
    for d in D:                           # split long sequences
        d = list(map(int, d))
        out += [d[i:i + max_len] for i in range(0, len(d), max_len)] if len(d) > max_len * 1.5 else [d]
    return [d for d in out if len(d) >= 64]
